import fs from "node:fs";
import path from "node:path";
import { ROOT_DIR } from "../config.js";
import { COMPARISON_SCHEMA, type ComparisonReport } from "../compare/comparison.js";
import { aggregateComparisons, policyOf, type ComparisonAggregate } from "../compare/evaluation.js";

// npm run compare:summary
//
// Every saved side-by-side comparison (eval/results/comparisons/), counted
// per case, Evidence Desk policy, evidence source and assessor, written to
// eval/results/comparisons/SUMMARY.md. Nothing is re-run or re-scored: each
// number is a count over the saved reports, shown as count/samples with its
// percentage, and every sample is listed so it can be opened.
// Why grouped by policy: samples made before and after Build 4 must never be
// counted together (docs/build-4-bank-return.md).

const dir = path.join(ROOT_DIR, "eval", "results", "comparisons");
const pct = (count: number, of: number) => `${count}/${of}${of ? ` (${Math.round((count / of) * 100)}%)` : ""}`;
const lines: string[] = [
  "# Saved side-by-side comparisons",
  "",
  "Generated by `npm run compare:summary` from the reports in this folder; nothing is re-run. Each count is over the samples of",
  "one configuration (count/samples, percentage). Live samples are separate runs of a small local model and vary; they are",
  "illustrations of behaviour, not rates. Deterministic samples repeat identically.",
  "",
  "Columns: **S** = Speck (Evidence Desk), **B** = the stateless baseline. \"Abstained (due)\" is abstaining where a conclusion",
  "was labelled; \"Abstained (right)\" is abstaining where the label is no conclusion. \"Replaced\" / \"Out of date\": samples whose",
  "presented support includes a record its source replaced / later restated. \"By corroboration\": Speck conclusions reached by",
  "rule corroborated-1 while Speck's own confidence was below its threshold.",
  ""
];

const groups = aggregateComparisons(dir);
for (const group of groups) lines.push(...section(group));
const out = path.join(dir, "SUMMARY.md");
fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`${groups.length} configuration(s), ${groups.reduce((sum, group) => sum + group.samples, 0)} saved comparison(s). Written ${path.relative(ROOT_DIR, out)}`);

function section(group: ComparisonAggregate): string[] {
  const n = group.samples;
  const text = [
    `## ${group.title}: ${group.kind}, ${group.assessor}, evidence ${group.evidence}`,
    "",
    `Policy: ${group.policy}. ${n} sample(s), ${group.first.slice(0, 16)} to ${group.last.slice(0, 16)} UTC.`,
    ""
  ];
  const rows: Array<[string, (side: ComparisonAggregate["stages"][number]["approaches"]["speck"]) => string]> = [
    ["Concluded", (a) => Object.entries(a.conclusions).map(([key, count]) => `${key === "none" ? "nothing" : key} ${count}`).join(", ")],
    ["Matches label", (a) => (a.matchesLabel === null ? "–" : pct(a.matchesLabel, n))],
    ["Unsupported conclusion", (a) => (a.unsupportedClaims === null ? "–" : pct(a.unsupportedClaims, n))],
    ["Abstained (due)", (a) => (a.inappropriateAbstentions === null ? "–" : pct(a.inappropriateAbstentions, n))],
    ["Abstained (right)", (a) => (a.appropriateAbstentions === null ? "–" : pct(a.appropriateAbstentions, n))],
    ["Followed a labelled change", (a) => (a.followedRevision === null ? "–" : pct(a.followedRevision, n))],
    ["Support includes a replaced record", (a) => pct(a.supportFromReplaced, n)],
    ["Support includes an out-of-date record", (a) => pct(a.supportFromOutdated, n)],
    ["Recorded why it changed", (a) => pct(a.recordsWhy, n)],
    ["By corroboration", (a) => pct(a.corroborated, n)],
    ["Errors", (a) => pct(a.errors, n)]
  ];
  for (const stage of group.stages) {
    text.push(`**${stage.stage}**${stage.label ? ` (label: ${stage.label})` : " (no label)"}`, "", "| | S | B |", "|---|---|---|");
    for (const [label, value] of rows) {
      const s = value(stage.approaches.speck);
      const b = label === "By corroboration" ? "–" : value(stage.approaches.stateless);
      text.push(`| ${label} | ${s} | ${b} |`);
    }
    text.push("");
  }
  text.push("<details><summary>Every sample</summary>", "", "| Sample | Models served | " + group.stages.map((stage) => stage.stage).join(" | ") + " |", `|---|---|${group.stages.map(() => "---").join("|")}|`);
  for (const report of samples(group)) {
    const served = [...new Set(report.stages.flatMap((stage) => [...(stage.stateless.model?.servedModels ?? []), ...(stage.speck.run?.servedModels ?? [])]))];
    const cell = (stage: ComparisonReport["stages"][number]) => {
      const s = stage.speck.error ? "S error" : `S ${stage.speck.concluded ?? `nothing${stage.speck.tentative ? ` (~${stage.speck.tentative} ${stage.speck.confidence})` : ""}`}${stage.speck.route === "corroboration" ? " [corroborated]" : ""}`;
      const b = stage.stateless.error ? "B error" : `B ${stage.stateless.concluded ?? "nothing"}${stage.checks.stateless.supportFromReplaced.length ? ` [cites replaced ${stage.checks.stateless.supportFromReplaced.join(",")}]` : ""}`;
      return `${s}; ${b}`;
    };
    text.push(`| \`${report.id}\` | ${served.join(", ") || "none (no model)"} | ${report.stages.map(cell).join(" | ")} |`);
  }
  text.push("", "</details>", "");
  return text;
}

function samples(group: ComparisonAggregate): ComparisonReport[] {
  const folder = path.join(dir, group.scenarioId);
  return fs.readdirSync(folder).filter((name) => name.endsWith(".json")).flatMap((name) => {
    try {
      const report = JSON.parse(fs.readFileSync(path.join(folder, name), "utf8")) as ComparisonReport;
      const assessor = report.configuration.assessor.kind === "nemotron" ? `Nemotron ${report.configuration.assessor.model}` : "deterministic rules";
      const evidence = report.configuration.evidence.mode === "zetaris" ? "Zetaris live" : "fixture file";
      return report.schema === COMPARISON_SCHEMA && report.kind === group.kind && assessor === group.assessor && evidence === group.evidence && policyOf(report) === group.policy ? [report] : [];
    } catch {
      return [];
    }
  }).sort((left, right) => left.finishedAt.localeCompare(right.finishedAt));
}
